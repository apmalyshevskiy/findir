/**
 * Знак суммы в плане бюджета.
 *
 * Отчёт складывает разделы: валовая прибыль = доходы + себестоимость, чистая —
 * плюс расходы. Факт приходит с готовыми знаками (обороты по П588/П589
 * умножаются на −1, расход по кассе и так отрицательный), поэтому и план должен
 * храниться так же: расход — минус. Это арифметика отчёта, менять её незачем.
 *
 * Помнить про минус должен не человек, а поле ввода:
 *
 *   набрали «100 000» в расходах  → сохранится −100 000
 *   набрали «−100 000»            → сохранится −100 000 (то же самое)
 *   набрали «+30 000»             → сохранится  +30 000 — возврат, уменьшение расхода
 *
 * Правило одно: явный знак всегда побеждает, а без знака подставляется знак
 * раздела. В поле правки знак показывается всегда — поэтому повторное
 * сохранение ничего не переворачивает, и возврат не превращается в расход.
 *
 * В ДДС и платёжном календаре разделов нет: там направление знает статья
 * движения, а не таблица, поэтому знак берётся из набранного, как раньше.
 */

/** Какой знак у раздела: −1 у расходных, +1 у остальных */
export const sectionSign = (section) => (section === 'expenses' || section === 'cost' ? -1 : 1)

// \s в JS-регулярке покрывает и неразрывный пробел — тот самый, которым
// toLocaleString разделяет триады и который приезжает вместе с вставкой
const clean = (text) => String(text ?? '').replace(/\s/g, '').replace(',', '.')

/** Текст поля → сумма для базы */
export function parsePlanAmount(text, sign = 1) {
  const s = clean(text)
  const n = parseFloat(s)
  if (!isFinite(n)) return 0
  return /^[+-]/.test(s) ? n : Math.abs(n) * sign
}

/** Сумма из базы → текст поля правки */
export function formatPlanAmount(amount, sign = 1) {
  const n = Math.round(Number(amount) || 0)
  if (n === 0) return ''
  // Плюс у возврата пишем явно: без него повторное сохранение вернуло бы
  // строке знак раздела, то есть возврат стал бы расходом
  return sign < 0 && n > 0 ? `+${n}` : String(n)
}
