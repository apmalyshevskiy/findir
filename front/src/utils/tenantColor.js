/**
 * Цвет компании в шапке.
 *
 * Финдиректор ведёт несколько клиентов, и цвет здесь не украшение: по нему
 * база узнаётся боковым зрением, ещё до того как прочитано название.
 *
 * Ряд собран из глубоких приглушённых тонов одной светлоты — они держатся
 * вместе с тёмно-синим логотипом и не спорят друг с другом. Звонкие красный
 * и зелёный сюда не берём: в приложении ими набран знак суммы (минус в
 * оборотке — красный, плюс — зелёный), и плашка такого же тона читалась бы
 * как «с этой компанией что-то не так».
 *
 * bg — заливка плашки (текст поверх белый), dot — точка внутри неё.
 */
export const PALETTE = [
  { key: 'wine',     name: 'винный',     bg: '#7f1d1d', dot: '#fca5a5' },
  { key: 'pine',     name: 'хвойный',    bg: '#134e4a', dot: '#5eead4' },
  { key: 'plum',     name: 'сливовый',   bg: '#581c87', dot: '#d8b4fe' },
  { key: 'chestnut', name: 'каштановый', bg: '#7c2d12', dot: '#fdba74' },
  { key: 'graphite', name: 'графит',     bg: '#1e293b', dot: '#94a3b8' },
  { key: 'fuchsia',  name: 'фуксия',     bg: '#701a75', dot: '#f0abfc' },
]

/** Запасной тон: пока компания не известна (первый заход, пустой список). */
export const FALLBACK = PALETTE[4]

// FNV-1a: короткая и хорошо перемешивает — домены вроде swa/swb различаются
// одним символом, и слабая хэш-функция дала бы им соседние индексы
const hash = (s) => {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}

/**
 * Тон по домену компании. Одинаков на любом устройстве — цвет привязан к
 * самой компании, а не к порядку подключения.
 */
export const tenantColor = (id) =>
  id ? PALETTE[hash(String(id)) % PALETTE.length] : FALLBACK

/**
 * Тона для списка компаний.
 *
 * База — тот же хэш, но внутри одного списка совпадения разводим: у двух
 * клиентов рядом одинаковый цвет обессмысливал бы саму затею. Сдвигаем к
 * ближайшему свободному, поэтому первые шесть компаний всегда разноцветные.
 */
export const tenantColors = (ids) => {
  const taken = new Set()
  const out   = new Map()

  for (const id of ids) {
    let i = hash(String(id)) % PALETTE.length

    // Разводим, только пока есть куда: компаний может быть больше, чем тонов
    if (taken.size < PALETTE.length) {
      while (taken.has(i)) i = (i + 1) % PALETTE.length
      taken.add(i)
    }
    out.set(id, PALETTE[i])
  }
  return out
}
