<?php

namespace App\Services;

/**
 * Системные категории платежа, на которые опирается КОД матчера.
 *
 * Это НЕ справочник категорий. Бизнес-категории (CUSTOMER_PAYMENT, TAX,
 * BANK_SERVICE и т.д.) живут в БД тенанта: их задают правила классификации
 * (payment_classification_rules) и карта разноски (category_postings).
 * Категории заводятся свободно — сидером, вручную или самообучением — и
 * НЕ валидируются против этого класса.
 *
 * Здесь остаются только две категории, которые матчер ставит сам, в коде:
 *  - TRANSFER — перевод между своими счетами (universal-правило, до таблицы);
 *  - OTHER    — ни одно правило не сработало, нужна ручная разметка.
 */
final class PaymentCategory
{
    /** Перемещение денег между своими счетами (ставится в коде, не правилом) */
    public const TRANSFER = 'TRANSFER';

    /** Правило не сработало → требуется ручная разметка */
    public const OTHER = 'OTHER';
}